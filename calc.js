/**
 * calc.js — расчётный модуль «Разбивка ГВС» (двухступенчатая смешанная схема).
 *
 * Чистые функции без побочных эффектов и без обращения к DOM — прямой перевод
 * формул строки 14 листа «Методика» исходного файла
 * «Разбивка ГВС для 2-х ступ. смеш..xls» в JS.
 *
 * Полное соответствие переменных ячейкам Excel — см. «Анализ_методики_ГВС.docx», раздел 6:
 *   z14 — общий расход ГВС, т/ч
 *   n14 — расход на отопление, зима, т/ч
 *   r14 — расход на отопление, точка излома, т/ч (= n14)
 *   o14 — нагрузка отопления, точка излома, Мкал/ч
 *   w14 — тепловая нагрузка I ступени ГВС, Мкал/ч
 *   g14 — тепловая нагрузка II ступени ГВС, Мкал/ч
 *   f14 — расход сетевой воды через II ступень, т/ч
 *   t14 — температура смеси перед I ступенью (T21), °C
 *   v14 — суммарный расход смеси через I ступень, т/ч
 *   u14 — температура возврата в тепловую сеть (T2), °C
 *
 * Работает и в браузере (глобальный объект GVS), и в Node (через module.exports) —
 * второе нужно, чтобы calc.test.js мог запускаться напрямую `node calc.test.js`
 * без сборки и без открытия браузера.
 */
(function (root) {
  'use strict';

  /**
   * @param {object} s - состояние расчёта:
   *   qGvs, qOt        — исходные нагрузки, Мкал/ч
   *   t1Winter,t2Winter— температуры сети зимой (подача/обратка), °C
   *   t1Break,t2Break  — температуры сети в точке излома (подача/обратка СО), °C
   *   tCold,tHot       — холодная вода / требуемая ГВС, °C
   *   e14              — Т сетевой воды после II ступени (регулируемая), °C
   *   y14              — Т воды ГВС после I ступени, промежуточная (регулируемая), °C
   * @returns {object} z14,n14,r14,o14,w14,g14,f14,t14,v14,u14
   */
  function calculate(s) {
    var z14 = s.qGvs / (s.tHot - s.tCold);
    var n14 = s.qOt / (s.t1Winter - s.t2Winter);
    var r14 = n14;
    var o14 = r14 * (s.t1Break - s.t2Break);
    var w14 = z14 * (s.y14 - s.tCold);
    var g14 = s.qGvs - w14;
    var f14 = g14 / (s.t1Break - s.e14);
    var t14 = (s.e14 * f14 + s.t2Break * r14) / (f14 + r14);
    var v14 = r14 + f14;
    var u14 = (v14 * t14 - w14) / v14;
    return {
      z14: z14, n14: n14, r14: r14, o14: o14, w14: w14,
      g14: g14, f14: f14, t14: t14, v14: v14, u14: u14
    };
  }

  var GVS = root.GVS = root.GVS || {};
  GVS.calculate = calculate;

  if (typeof module !== 'undefined' && module.exports) {
    module.exports = { calculate: calculate };
  }
})(typeof window !== 'undefined' ? window : globalThis);
